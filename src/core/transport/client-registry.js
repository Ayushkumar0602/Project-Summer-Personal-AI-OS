/**
 * core/transport/client-registry.js
 *
 * Tracks every connected client (Mac Electron, iPhone, future Android, CLI…).
 * Manages session ownership — only ONE client "owns" Summer's attention at a time.
 *
 * Design principles:
 *  1. Platform-blind  — registry doesn't care what type of client connects.
 *  2. Immutable records — use register/unregister, never mutate client objects.
 *  3. Priority-based ownership — Desktop > Mobile > Web > CLI (overridable).
 */

'use strict';

const { createLogger } = require('../utils/logger');
const bus = require('../event-bus');

const log = createLogger('ClientRegistry');

// Platform priority — higher = preferred session owner
const PLATFORM_PRIORITY = {
    electron: 100,  // Mac/Win/Linux desktop
    ios:       80,
    android:   80,
    web:       60,
    cli:       40,
    unknown:   20,
};

class ClientRegistry {
    constructor() {
        /** @type {Map<string, ClientRecord>} */
        this._clients = new Map();

        /** ID of the client that currently "owns" the session */
        this._activeClientId = null;

        /** @type {Map<string, string[]>} Queue of messages keyed by platform (e.g. 'electron') */
        this._offlineQueue = new Map();
    }

    // ── Registration ──────────────────────────────────────────────────────────

    /**
     * Register a newly connected client.
     * @param {string} clientId     - unique ID (generated by transport layer)
     * @param {object} capabilities - from client_hello message
     * @param {Function} sendFn     - (encodedMessage: string) => void  to send to this client
     */
    register(clientId, capabilities = {}, sendFn) {
        const record = {
            id:         clientId,
            platform:   capabilities.platform   || 'unknown',
            deviceName: capabilities.deviceName  || 'Unknown Device',
            pushToken:  capabilities.pushToken   || null,  // APNs / FCM for offline notify
            hasMic:     capabilities.hasMic     ?? true,
            hasScreen:  capabilities.hasScreen  ?? true,
            supportedActions: capabilities.supportedActions || null, // null = supports all
            connectedAt: Date.now(),
            send:       sendFn,  // private — only send() below uses this
        };

        this._clients.set(clientId, record);
        log.info(`Client connected: [${record.platform}] ${record.deviceName} (${clientId})`);

        bus.dispatch(bus.EVENTS.CLIENT_CONNECTED, {
            clientId,
            platform:   record.platform,
            deviceName: record.deviceName,
            hasMic:     record.hasMic,
        });

        // Auto-assign session ownership if nothing active or this client has higher priority
        this._evaluateOwnership(clientId);

        // Drain offline queue for this platform
        if (this._offlineQueue.has(record.platform)) {
            const queue = this._offlineQueue.get(record.platform);
            if (queue && queue.length > 0) {
                log.info(`Draining ${queue.length} offline queued messages for platform [${record.platform}]`);
                queue.forEach(msg => this._sendSafe(record, msg));
                this._offlineQueue.set(record.platform, []);
            }
        }
    }

    /**
     * Unregister a disconnected client.
     */
    unregister(clientId) {
        const record = this._clients.get(clientId);
        if (!record) return;

        this._clients.delete(clientId);
        log.info(`Client disconnected: [${record.platform}] ${record.deviceName} (${clientId})`);

        bus.dispatch(bus.EVENTS.CLIENT_DISCONNECTED, { clientId });

        // Re-elect owner if the active client left
        if (this._activeClientId === clientId) {
            this._activeClientId = null;
            this._electNewOwner();
        }
    }

    // ── Session ownership ─────────────────────────────────────────────────────

    /** @returns {ClientRecord|null} */
    getActiveClient() {
        return this._clients.get(this._activeClientId) || null;
    }

    /** @returns {string|null} */
    getActiveClientId() {
        return this._activeClientId;
    }

    /**
     * Manually transfer ownership to a specific client.
     * Used when user says "Hey Summer, switch to my phone."
     */
    transferOwnership(clientId) {
        if (!this._clients.has(clientId)) {
            log.warn(`transferOwnership: client ${clientId} not found`);
            return false;
        }
        this._activeClientId = clientId;
        log.info(`Session ownership transferred → ${clientId}`);
        return true;
    }

    _evaluateOwnership(newClientId) {
        if (!this._activeClientId) {
            this._activeClientId = newClientId;
            log.info(`Session owner elected: ${newClientId}`);
            return;
        }

        const current  = this._clients.get(this._activeClientId);
        const incoming = this._clients.get(newClientId);
        if (!incoming) return;

        const currentPriority  = PLATFORM_PRIORITY[current?.platform  || 'unknown'] || 0;
        const incomingPriority = PLATFORM_PRIORITY[incoming.platform  || 'unknown'] || 0;

        if (incomingPriority > currentPriority) {
            this._activeClientId = newClientId;
            log.info(`Session ownership upgraded: ${current?.platform} → ${incoming.platform}`);
        }
    }

    _electNewOwner() {
        if (this._clients.size === 0) {
            log.info('No clients connected — daemon running headless.');
            return;
        }
        // Pick highest-priority remaining client
        let bestId = null;
        let bestPriority = -1;
        for (const [id, record] of this._clients) {
            const priority = PLATFORM_PRIORITY[record.platform] || 0;
            if (priority > bestPriority) {
                bestPriority = priority;
                bestId = id;
            }
        }
        this._activeClientId = bestId;
        if (bestId) log.info(`New session owner elected: ${bestId}`);
    }

    // ── Sending ───────────────────────────────────────────────────────────────

    /**
     * Send an encoded message to a specific client.
     * @param {string} clientId
     * @param {string} encodedMsg  - output of protocol.encode()
     */
    send(clientId, encodedMsg) {
        const record = this._clients.get(clientId);
        if (!record) return;
        try {
            record.send(encodedMsg);
        } catch (err) {
            log.error(`Send failed to ${clientId}:`, { err: err.message });
        }
    }

    _sendSafe(record, encodedMsg) {
        try {
            record.send(encodedMsg);
        } catch (err) {
            log.error(`Send safe failed to ${record.id}:`, { err: err.message });
        }
    }

    /**
     * Send a raw message specifically to the highest-priority client of a specific platform.
     * Use this for platform-specific tasks (e.g., Mac screenshot must go to Mac).
     * If no client of that platform is online, the message is queued for when they reconnect.
     * @param {string} platform - e.g., 'electron', 'ios'
     * @param {string} encodedMessage
     */
    sendToPlatform(platform, encodedMessage) {
        if (!platform || !encodedMessage) return;

        let bestClient = null;
        for (const client of this._clients.values()) {
            if (client.platform === platform) {
                if (!bestClient || client.connectedAt < bestClient.connectedAt) {
                    bestClient = client; // prefer oldest connected (most stable)
                }
            }
        }

        if (bestClient) {
            this._sendSafe(bestClient, encodedMessage);
        } else {
            // Queue for later when the device comes online (Problem B Solution)
            log.warn(`No active client found for platform [${platform}]. Queuing message for reconnect.`);
            if (!this._offlineQueue.has(platform)) {
                this._offlineQueue.set(platform, []);
            }
            this._offlineQueue.get(platform).push(encodedMessage);
        }
    }

    /**
     * Broadcast to ALL connected clients.
     * @param {string} encodedMsg
     */
    broadcast(encodedMsg) {
        for (const [id] of this._clients) {
            this.send(id, encodedMsg);
        }
    }

    /**
     * Send to the active (session-owning) client only.
     * @param {string} encodedMsg
     */
    sendToActive(encodedMsg) {
        if (this._activeClientId) this.send(this._activeClientId, encodedMsg);
    }

    // ── Queries ───────────────────────────────────────────────────────────────

    /** @returns {ClientRecord[]} */
    getAllClients() {
        return Array.from(this._clients.values());
    }

    count() {
        return this._clients.size;
    }

    isClientActive(clientId) {
        return this._activeClientId === clientId;
    }

    /**
     * Get capabilities of the active (session-owning) client.
     * Used by tool-router to filter which tools to send to Gemini.
     * @returns {{ platform: string, hasMic: boolean, hasScreen: boolean, supportedActions: string[]|null }}
     */
    getActiveCapabilities() {
        const record = this.getActiveClient();
        if (!record) return { platform: 'unknown', hasMic: true, hasScreen: true, supportedActions: null };
        return {
            platform:         record.platform,
            hasMic:           record.hasMic,
            hasScreen:        record.hasScreen,
            supportedActions: record.supportedActions,
        };
    }

    /** Alias for settings IPC — returns safe serializable list */
    getAll() {
        return Array.from(this._clients.values()).map(r => ({
            id:          r.id,
            platform:    r.platform,
            deviceName:  r.deviceName,
            hasMic:      r.hasMic,
            hasScreen:   r.hasScreen,
            supportedActions: r.supportedActions,
            connectedAt: r.connectedAt,
            isActive:    r.id === this._activeClientId,
        }));
    }
}

module.exports = new ClientRegistry(); // Singleton
